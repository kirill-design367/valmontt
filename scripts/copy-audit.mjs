/** Видимый текст: без скриптов, стилей и самих тегов. */
const видимый = (html) =>
  html
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&[a-z]+;/gi, ' ')
    .replace(/\s+/g, ' ')

const плохо = []

for (const [имя, файл] of СТРАНИЦЫ) {
  const html = fs.readFileSync(path.join(OUT, файл), 'utf8')
  const текст = видимый(html)

  for (const слово of ЗАПРЕЩЕНО) {
    const i = текст.toLowerCase().indexOf(слово)
    if (i !== -1) плохо.push(`${имя}: мистика «${текст.slice(Math.max(0, i - 40), i + 40).trim()}»`)
  }

  // Латиница в видимом тексте
  const латинские = текст.match(/[A-Za-z]{2,}/g) ?? []
  if (латинские.length) плохо.push(`${имя}: латиница в видимом тексте — ${[...new Set(латинские)].join(', ')}`)

  // Мета-описание проверяем отдельно: в видимый текст оно не попадает
  const мета = html.match(/<meta name="description" content="([^"]+)"/)?.[1] ?? ''
  for (const слово of ЗАПРЕЩЕНО) {
    if (мета.toLowerCase().includes(слово)) плохо.push(`${имя}: мистика в мета-описании — «${мета}»`)
  }

  const нужны = ОБЯЗАНЫ[файл] ?? []
  const нет = нужны.filter((ф) => !html.includes(ф))
  if (нет.length) плохо.push(`${имя}: не найдены формулировки — ${нет.join(' | ')}`)

  console.log(`${имя.padEnd(12)} знаков видимого текста ${String(текст.length).padStart(5)}   формулировок ${нужны.length - нет.length}/${нужны.length}`)
}

if (плохо.length) {
  console.error('\nПРОБЛЕМЫ:')
  плохо.forEach((x) => console.error(' •', x))
  process.exit(1)
}
