#!/usr/bin/env python3
"""
Куда поставить маркер на каждом снимке.

Безопасная рамка взята не на глаз, а из фактического замера обвязки кадра
(scripts/marker-zone.mjs): шапка, вертикальный номер кадра, нижняя подпись,
счётчик прогресса, плюс то, что срезает object-fit: cover на рабочих
разрешениях.

Внутри рамки ищем участок, где кружок 1 px будет виден, а рисунок под ним
не спорит с ним: низкая средняя яркость и низкий разброс — ровная тьма, а
не текстура. Центр кадра исключён отдельно: маркер там читается как часть
композиции, а не как метка.
"""
from PIL import Image, ImageFilter
import statistics

# доли снимка, из замера
ЗОНА = {
    'wide': dict(x0=0.25, x1=0.78, y0=0.20, y1=0.60),
    'tall': dict(x0=0.20, x1=0.84, y0=0.28, y1=0.70),
}
# зона, где маркер выглядит как часть композиции, а не как метка
ЦЕНТР = dict(x0=0.40, x1=0.60, y0=0.40, y1=0.60)

# диаметр маркера в долях снимка на самом тесном рабочем разрешении
ОКНО = {'wide': (64 / 1613, 64 / 900), 'tall': (64 / 390, 64 / 699)}

КАДРЫ = ['doroga', 'vorota', 'zal', 'terrasa']
ИМЕНА = {'doroga': 'ДОРОГА', 'vorota': 'ВОРОТА', 'zal': 'ВЕРХНИЙ ЗАЛ', 'terrasa': 'ТЕРРАСА'}

ШАГ = 0.01


def оценить(im, кадр, зона, окно):
    W, H = im.size
    ow, oh = окно
    # запас в половину диаметра — маркер не должен цеплять край зоны
    лучшие = []
    x = зона['x0'] + ow / 2
    while x <= зона['x1'] - ow / 2 + 1e-9:
        y = зона['y0'] + oh / 2
        while y <= зона['y1'] - oh / 2 + 1e-9:
            в_центре = (ЦЕНТР['x0'] < x < ЦЕНТР['x1']) and (ЦЕНТР['y0'] < y < ЦЕНТР['y1'])
            if not в_центре:
                # окно берём в полтора маркера: важно и то, что вокруг
                bx = int((x - ow * 0.75) * W)
                by = int((y - oh * 0.75) * H)
                bw = max(2, int(ow * 1.5 * W))
                bh = max(2, int(oh * 1.5 * H))
                patch = im.crop((bx, by, bx + bw, by + bh))
                px = list(patch.getdata())
                сред = sum(px) / len(px)
                разброс = statistics.pstdev(px)
                # штраф за близость к краю безопасной зоны — маркеру нужен воздух
                край = min(
                    (x - зона['x0']) / (зона['x1'] - зона['x0']),
                    (зона['x1'] - x) / (зона['x1'] - зона['x0']),
                    (y - зона['y0']) / (зона['y1'] - зона['y0']),
                    (зона['y1'] - y) / (зона['y1'] - зона['y0']),
                )
                штраф = 0 if край > 0.12 else (0.12 - край) * 300
                лучшие.append((сред + разброс * 1.4 + штраф, round(x, 3), round(y, 3), сред, разброс))
            y += ШАГ
        x += ШАГ
    лучшие.sort()
    return лучшие


print(f"{'кадр':<14}{'вид':<6}{'x':>7}{'y':>7}{'яркость':>10}{'разброс':>10}")
итог = {}
for кадр in КАДРЫ:
    итог[кадр] = {}
    for вид in ('wide', 'tall'):
        im = Image.open(f'public/place/{кадр}-{вид}.jpg').convert('L')
        # лёгкое размытие: нас интересует пятно, а не отдельный шумный пиксель
        im = im.filter(ImageFilter.GaussianBlur(1.2))
        топ = оценить(im, кадр, ЗОНА[вид], ОКНО[вид])
        _, x, y, сред, разброс = топ[0]
        итог[кадр][вид] = (x, y)
        print(f'{ИМЕНА[кадр]:<14}{вид:<6}{x:>7.3f}{y:>7.3f}{сред:>10.1f}{разброс:>10.1f}')

print('\nconst МАРКЕРЫ = [')
for кадр in КАДРЫ:
    w = итог[кадр]['wide']
    t = итог[кадр]['tall']
    print(
        f"  {{ wide: {{ x: {w[0]}, y: {w[1]} }}, tall: {{ x: {t[0]}, y: {t[1]} }} }}, // {ИМЕНА[кадр].lower()}"
    )
print(']')
